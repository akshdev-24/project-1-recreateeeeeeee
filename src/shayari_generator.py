"""Gemini-powered Roman Hindi/Hinglish Shayari generator.

Gemini is used ONLY for generating Shayari.
Titles, descriptions, tags, hashtags, SEO keywords and queries
are NEVER generated by Gemini.

The module automatically switches between configured Gemini models
when one model fails or is unavailable.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

from google import genai


# ============================================================
# PATHS
# ============================================================

ROOT_DIR = Path(__file__).resolve().parent.parent

HISTORY_FILE = ROOT_DIR / "content_history.json"


# ============================================================
# GEMINI MODEL CONFIGURATION
# ============================================================

# Models are tried in this order.
#
# Example:
# 1. gemini-3.6-flash
# 2. gemini-3.6-flash-lite
# 3. gemini-2.5-flash
#
# If the first model fails, the next model is automatically tried.

DEFAULT_MODELS = [
    "gemini-3.6-flash",
    "gemini-3.6-flash-lite",
    "gemini-2.5-flash",
]


def get_models() -> list[str]:
    """Return Gemini models configured through GEMINI_MODELS.

    Environment example:

        GEMINI_MODELS=gemini-3.6-flash,gemini-3.6-flash-lite,gemini-2.5-flash

    If GEMINI_MODELS is not provided, DEFAULT_MODELS are used.
    """

    raw_models = os.getenv("GEMINI_MODELS", "").strip()

    if not raw_models:
        return DEFAULT_MODELS.copy()

    models = [
        model.strip()
        for model in raw_models.split(",")
        if model.strip()
    ]

    # Remove duplicates while preserving order.
    models = list(dict.fromkeys(models))

    return models or DEFAULT_MODELS.copy()


