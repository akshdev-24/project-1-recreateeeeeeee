# ============================================================
# GEMINI GENERATION
# ============================================================

def generate_shayari() -> dict[str, str]:
    """Generate one Shayari using automatic Gemini model fallback.

    Returns:

        {
            "shayari": "..."
        }

    This function intentionally accepts NO title argument so it
    remains compatible with the existing main.py.
    """

    client = get_client()

    models = get_models()

    errors: list[str] = []

    print()
    print("=" * 60)
    print("🤖 GEMINI SHAYARI GENERATION")
    print("=" * 60)
    print(f"Models configured: {', '.join(models)}")
    print()

    # --------------------------------------------------------
    # Try every configured Gemini model.
    # --------------------------------------------------------

    for index, model in enumerate(models, start=1):

        print(
            f"🔄 Gemini model attempt "
            f"{index}/{len(models)}: {model}"
        )

        try:

            response = client.models.generate_content(
                model=model,
                contents=GENERATION_PROMPT,
            )

            shayari = _parse_shayari_response(
                response
            )

            # ------------------------------------------------
            # Basic validation.
            # ------------------------------------------------

            shayari = shayari.strip()

            if not shayari:
                raise RuntimeError(
                    "Generated Shayari is empty."
                )

            print(
                f"✅ Gemini generation successful "
                f"using: {model}"
            )

            print("=" * 60)
            print()

            return {
                "shayari": shayari
            }

        except Exception as exc:

            error_message = (
                str(exc)
                .replace("\n", " ")
                .strip()
            )

            # Prevent extremely long logs.
            if len(error_message) > 500:
                error_message = (
                    error_message[:500] + "..."
                )

            errors.append(
                f"{model}: {error_message}"
            )

            print(
                f"❌ Gemini model failed: {model}"
            )

            print(
                f"   Error: {error_message}"
            )

            # ------------------------------------------------
            # Automatically switch to next model.
            # ------------------------------------------------

            if index < len(models):

                next_model = models[index]

                print()
                print(
                    f"➡️ Automatically switching "
                    f"to next model: {next_model}"
                )
                print()

    # ========================================================
    # ALL MODELS FAILED
    # ========================================================

    print()
    print("=" * 60)
    print("⚠️ ALL GEMINI MODELS FAILED")
    print("=" * 60)

    for error in errors:
        print(f"- {error}")

    print()
    print(
        "🛟 Using local fallback Shayari."
    )
    print("=" * 60)
    print()

    return local_fallback(
        load_history()
    )


# ============================================================
# LOCAL FALLBACK
# ============================================================

def local_fallback(
    history: list[dict[str, Any]] | None = None,
) -> dict[str, str]:
    """Return an unused local fallback Shayari.

    Attempts to avoid repeating a fallback Shayari that already
    exists in content_history.json.
    """

    history = history or []

    used_shayari = {
        str(item.get("shayari", "")).strip()
        for item in history
        if isinstance(item, dict)
    }

    # --------------------------------------------------------
    # Find first unused fallback.
    # --------------------------------------------------------

    for text in FALLBACK_SHAYARI:

        cleaned = text.strip()

        if cleaned not in used_shayari:

            return {
                "shayari": cleaned
            }

    # --------------------------------------------------------
    # If all fallbacks were used, cycle back to first.
    # --------------------------------------------------------

    return {
        "shayari": FALLBACK_SHAYARI[0].strip()
    }


# ============================================================
# OPTIONAL SAFE HELPER
# ============================================================

def validate_shayari(shayari: str) -> str:
    """Clean and validate Shayari before video generation."""

    if not isinstance(shayari, str):
        raise TypeError(
            "Shayari must be a string."
        )

    shayari = shayari.strip()

    if not shayari:
        raise ValueError(
            "Shayari cannot be empty."
        )

    return shayari


