# ============================================================
# GEMINI CLIENT
# ============================================================

def get_client() -> genai.Client:
    """Create and return Gemini client."""

    api_key = os.getenv("GOOGLE_API_KEY", "").strip()

    if not api_key:
        raise RuntimeError(
            "GOOGLE_API_KEY environment variable is missing."
        )

    return genai.Client(api_key=api_key)


# ============================================================
# HISTORY
# ============================================================

def load_history() -> list[dict[str, Any]]:
    """Load previously generated Shayari history."""

    if not HISTORY_FILE.exists():
        return []

    try:
        data = json.loads(
            HISTORY_FILE.read_text(encoding="utf-8")
        )

        if isinstance(data, list):
            return data

        if isinstance(data, dict):
            items = data.get("items")

            if isinstance(items, list):
                return items

    except Exception as exc:
        print(
            f"Warning: could not read content history: "
            f"{exc}"
        )

    return []


def save_history(item: dict[str, Any]) -> None:
    """Append a generated item to content history."""

    history = load_history()

    history.append(item)

    # Keep only the latest 500 entries.
    history = history[-500:]

    HISTORY_FILE.write_text(
        json.dumps(
            history,
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )


# ============================================================
# RESPONSE PARSER
# ============================================================

def _parse_shayari_response(response: Any) -> str:
    """Extract Shayari text from Gemini response.

    Gemini is requested to return JSON:

        {
            "shayari": "..."
        }

    But this parser also handles plain text responses safely.
    """

    text = getattr(response, "text", "") or ""

    text = text.strip()

    if not text:
        raise RuntimeError(
            "Gemini returned an empty response."
        )

    # --------------------------------------------------------
    # Remove Markdown code fences if Gemini returns them.
    # --------------------------------------------------------

    if text.startswith("```"):

        text = text.strip("`").strip()

        if text.lower().startswith("json"):
            text = text[4:].strip()

    # --------------------------------------------------------
    # Try JSON first.
    # --------------------------------------------------------

    try:

        data = json.loads(text)

        if isinstance(data, dict):

            shayari = str(
                data.get("shayari", "")
            ).strip()

            if shayari:
                return shayari

    except json.JSONDecodeError:
        pass

    # --------------------------------------------------------
    # If JSON parsing fails, use plain response.
    # --------------------------------------------------------

    if text:
        return text

    raise RuntimeError(
        "Gemini returned empty Shayari."
    )


